"""Core data contracts for the pipeline.
Proposition's shape is frozen (CoVe depends on it exactly as-is); everything is immutable except RequestContext, which is per-request and never global."""
from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

ProvenanceTier = Literal["retrieved", "derived", "external"]
IngestionPath = Literal["A_unstructured", "B_structured"]
Scale = Literal["unit", "thousands", "millions", "billions"]
NumericUnit = Literal["percent", "ratio", "absolute", "count"]
PeriodBasis = Literal["reported", "ttm", "restated"]
ExtractionTier = Literal["xbrl", "rules", "llm_qualifier"]
FilingType = Literal["10-K", "10-Q", "8-K", "transcript", "annual_report", "csv", "xlsx"]
Quarter = Literal[1, 2, 3, 4]
Verdict = Literal["match", "conflict", "unsupported"]


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class Period(_Frozen):
    fiscal_year: int
    quarter: Optional[Quarter] = None
    basis: PeriodBasis = "reported"


class NumericRecord(_Frozen):
    """Digits here are always copied verbatim from source, never generated by a model."""

    value: float
    scale: Scale
    currency: Optional[str] = None
    unit: NumericUnit
    period: Period


class Confidence(_Frozen):
    ocr_confidence: float = 1.0
    extraction_tier: ExtractionTier


class PropositionMetadata(_Frozen):
    company: str
    ticker: Optional[str] = None
    filing_type: FilingType
    filing_date: str
    section: str
    page: int  # zero-indexed — keep this convention consistent everywhere
    source_uri: str


class Proposition(_Frozen):
    """The atomic retrievable unit shared by all three indexes."""

    proposition_id: str
    text: str
    provenance_tier: ProvenanceTier
    ingestion_path: IngestionPath
    numeric: Optional[NumericRecord] = None
    confidence: Confidence
    metadata: PropositionMetadata
    # Which financial metrics this fact is about (step 1.4's metric filter).
    # Empty means "not labelled yet", not "about nothing" -- see offline/labeling/metric_labeler.py.
    metrics: tuple[str, ...] = ()


class PolicyFact(_Frozen):
    """The atomic retrievable unit for a non-finance document (a policy,
    procedure, form, or FAQ) -- work package 3's ingest of documents other
    than financial filings.

    Not a sentence, on purpose: a rule is incomplete without its conditions
    and exceptions ("minors may open an account" is dangerous read alone,
    without "provided a guardian co-signs"). One PolicyFact is one whole
    rule block -- typically a numbered clause or a full paragraph under one
    heading -- kept together with the heading path above it so a citation
    can point at exactly where it came from.
    """

    fact_id: str
    document_id: str
    text: str  # the rule block, verbatim from the source, never rephrased
    section_path: tuple[str, ...] = ()  # heading hierarchy, e.g. ("Accounts", "Eligibility", "Minors")
    section_number: Optional[str] = None  # e.g. "4.2.1", when the document numbers its own clauses
    # Structured extraction, rule-based for now (offline/documents/rule_extractor.py):
    # antecedent (who/when) is not yet reliably extractable without a model
    # and is left None rather than guessed; consequent and exceptions are.
    antecedent: Optional[str] = None
    consequent: Optional[str] = None
    exceptions: tuple[str, ...] = ()
    page: int = 0  # zero-indexed, same convention as PropositionMetadata.page
    source_uri: str = ""


class SourceRef(_Frozen):
    """Built deterministically from proposition metadata — never model output."""

    filing_type: FilingType
    filing_date: str
    page: int


class FFF(_Frozen):
    """Fully-Formatted Fact — a structured record rendered deterministically into text."""

    fff_id: str
    proposition_id: str
    subject: str  # placeholder token, e.g. "<ENT_1>"
    metric: str
    period_label: str
    value_text: str
    provenance_tier: ProvenanceTier
    source_ref: SourceRef

    def render(self) -> str:
        """Renders one fact per line. Plain string templating, no model involved."""
        return (
            f"{self.subject} {self.metric} for {self.period_label} was {self.value_text} "
            f"[src: {self.source_ref.filing_type} filed {self.source_ref.filing_date}, "
            f"p.{self.source_ref.page}]."
        )


class CanonicalIdentifiers(_Frozen):
    ticker: Optional[str] = None
    cik: Optional[str] = None


class PlaceholderRegistryEntry(_Frozen):
    """One entry in the placeholder registry."""

    surface_form: str
    placeholder: str
    canonical: CanonicalIdentifiers


class SubQuery(_Frozen):
    """One entity, one metric, one period — the unit the query split guarantees.
    period is structured for filtering; period_label is the rendered form used in FFFs/prompts."""

    sub_query_id: str
    entity: str
    metric: str
    period: Period
    period_label: str
    filing_types: tuple[FilingType, ...] = ()


CollisionAxis = Literal["temporal", "entity", "metric"]


class CollisionTag(_Frozen):
    """A detected collision, tagged by axis (temporal/entity/metric).
    members holds the colliding items: placeholders, metric ids, or period labels depending on axis."""

    axis: CollisionAxis
    members: tuple[str, ...]


class VerificationClaimResult(_Frozen):
    """One row of CoVe's per-claim verification trace."""

    claim_id: str
    claim_text: str
    is_numeric: bool
    verdict: Verdict
    supporting_fff_ids: tuple[str, ...] = ()


class VerifiedAnswer(_Frozen):
    """`Verifier.verify()` return type. With CoVe off, this just passes the draft
    through unchanged with an empty trace."""

    answer_text: str
    verification_trace: tuple[VerificationClaimResult, ...] = ()


class RequestContext(BaseModel):
    """Per-request state threaded through the pipeline. Never store this in a global."""

    model_config = ConfigDict(extra="forbid")

    request_id: str
    config_hash: str
    placeholder_map: dict[str, str] = Field(default_factory=dict)
    sub_queries: list[SubQuery] = Field(default_factory=list)
    fff_sets: dict[str, list[FFF]] = Field(default_factory=dict)
    verification_trace: list[VerificationClaimResult] = Field(default_factory=list)
    collision_tags: list[CollisionTag] = Field(default_factory=list)
